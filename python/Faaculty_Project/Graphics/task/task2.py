from turtle import *
t = Turtle()
t.fillcolor("red")
t.penup()
t.goto(-150, 100)
t.begin_fill()
t.pendown()
t.forward(150)
t.right(45)
t.forward(100)
t.right(135)
t.forward(290)
t.right(135)
t.forward(100)
t.right(45)
t.end_fill()
t.penup()
t.goto(-300, -50)
t.pendown()
t.fillcolor("red")
t.begin_fill()
t.forward(450)
t.left(90)
t.forward(80)
t.left(90)
t.forward(450)
t.left(90)
t.forward(75)
t.end_fill()
t.penup()
t.goto(-250, -60)
t.pendown()
t.fillcolor("yellow")
t.begin_fill()
t.circle(25)
t.end_fill()
t.penup()
t.goto(50, -60)
t.pendown()
t.fillcolor("yellow")
t.begin_fill()
t.circle(25)
t.end_fill()
done()
